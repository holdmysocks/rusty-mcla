//! The general 4 x 4 inverse by cofactors as the original runs it: F-62799 (the determinant), F-25750 (the inverse in
//! place: 1 / determinant, no guard for a singular matrix, so it gives infinities and NaN) and F-25548 (the same into
//! another matrix, never reached in the game). The three are transcriptions, instruction for instruction, of the
//! generated code (tools/recomp_scalar_to_rust.py wrote the functions below from it: the scalar registers as f64
//! holding single values, each operation rounded to single, the fused ones a single `mul_add` then the single
//! rounding, the stack frame as an array); an offline run of the originals on 6,000 matrices compares them word for
//! word (tools/inverse4_reference.py, test `inverse4_matches_the_original`).
//!
//! The guest's matrix is 16 floats, rows of four (rows 0-2 the axes, row 3 the place); a glam `Mat4` holds the same
//! words as its columns, so [`inverse_of`] takes and gives a `Mat4` with no transpose.
#![allow(clippy::all, unused_variables, unused_mut)]

use glam::Mat4;

