fn words(m: &[f32; 16]) -> [u32; 16] {
    m.map(f32::to_bits)
}

fn floats(w: &[u32; 16]) -> [f32; 16] {
    w.map(f32::from_bits)
}

/// F-62799: the determinant of the matrix.
pub fn det4(m: &[f32; 16]) -> f32 {
    det_f62799(&mut words(m), &mut [0; 16]) as f32
}

/// F-25750: the inverse of `m` (in place in the original).
pub fn inverse4(m: &[f32; 16]) -> [f32; 16] {
    let mut w = words(m);
    inv_f25750(&mut w, &mut [0; 16]);
    floats(&w)
}

/// F-25548: the inverse of `m` written to another matrix.
pub fn inverse4_to(m: &[f32; 16]) -> [f32; 16] {
    let mut out = [0u32; 16];
    inv_f25548(&mut out, &mut words(m));
    floats(&out)
}

/// F-25750 for the port's `Mat4`.
pub fn inverse_of(m: &Mat4) -> Mat4 {
    Mat4::from_cols_array(&inverse4(&m.to_cols_array()))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn h(x: &str) -> u32 {
        u32::from_str_radix(x, 16).unwrap()
    }
    fn nan(x: u32) -> u32 {
        if f32::from_bits(x).is_nan() { 0x7fc0_0000 } else { x }
    }

    /// The determinant, the inverse in place and the inverse into another matrix on 6,000 matrices (general, rigid
    /// frames, scaled and a little off square, singular, permutations and over many magnitudes, a few with NaN and
    /// infinite lanes): every word equal (a NaN only as a NaN).
    #[test]
    fn inverse4_matches_the_original() {
        let mut n = 0;
        for line in include_str!("../testdata/inverse4_ref.txt").lines() {
            let (case, want) = line.split_once(" -> ").unwrap();
            let m: Vec<f32> = case.split(' ').map(|x| f32::from_bits(h(x))).collect();
            let m: [f32; 16] = m.try_into().unwrap();
            let mut parts = want.split(" |");
            let det = h(parts.next().unwrap().trim());
            let inv: Vec<u32> = parts.next().unwrap().split_whitespace().map(h).collect();
            let to: Vec<u32> = parts.next().unwrap().split_whitespace().map(h).collect();
            assert_eq!(nan(det4(&m).to_bits()), nan(det), "det {line}");
            assert_eq!(inverse4(&m).map(|x| nan(x.to_bits())).to_vec(), inv.iter().map(|&x| nan(x)).collect::<Vec<_>>(), "inverse {line}");
            assert_eq!(inverse4_to(&m).map(|x| nan(x.to_bits())).to_vec(), to.iter().map(|&x| nan(x)).collect::<Vec<_>>(), "inverse to {line}");
            n += 1;
        }
        assert_eq!(n, 6000);
    }
}
