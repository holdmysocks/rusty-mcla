/// The slots `scene` passes to UseRacerNativeCharacter.
pub fn native_slots(scene: &str) -> u16 {
    NATIVE_SLOTS.iter().find(|r| r.0.eq_ignore_ascii_case(scene)).map_or(0, |r| r.1)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The car arrest scenes show slot 0 (the player in his car), the bikestand nobody; a racestarter all eight.
    #[test]
    fn scene_slots() {
        for s in ["cut_cop_arrest", "cut_cop_arrest_02", "cut_cop_arrest_03", "cut_cop_arrest_07", "cut_cop_arrest_08"] {
            assert_eq!(native_slots(s), 1, "{s}");
        }
        assert_eq!(native_slots("cut_cop_arrest_bikestand"), 0);
        assert_eq!(native_slots("racestart/cut_racestarter_1x8_01"), 0xff);
        assert_eq!(native_slots("story/cut_story_race_gh_06"), 3);
        assert!(DRIVER_EVENTS.contains(&("cut_cop_walk_plyr_02", true, 0, 4.66667)));
        let mut names: Vec<&str> = NATIVE_SLOTS.iter().map(|r| r.0).collect();
        names.dedup();
        assert_eq!(names.len(), NATIVE_SLOTS.len());
    }
}
