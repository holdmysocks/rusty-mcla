//! The in-car driver in a cine scene (docs/reference/hookmen/bikestand_rider.md). A racer's driver is an
//! mcCharacterPlus; its +420 is the scene show flag (vt+56 F-99669 sets it, the instance reset vt+8 F-94693 clears it).
//! While a scene plays (the scene byte, set by the scene start F-37136 and cleared by FinishScene F-65984) the draw
//! gate F-14542 draws a driver only with +420 set. +420 follows racer +676 (F-13669 -> F-30339 -> F-89814 -> F-56593;
//! a driver loaded later takes it, F-14308 / F-87122), set by:
//! - EndDescription (F-39589) at the scene's start: every slot the scene script passed to
//!   CineScript_UseRacerNativeCharacter(n) (F-94066: the flag mgr+3876+n, for any slot and the local human too);
//! - the cine events showdriver (11) / hidedriver (12) on the event's car slot (F-91263).
//! FinishScene clears the slot flags but never racer +676, so the flag outlives the scene; ResetWithDamageIntact
//! (F-39106) and Racer Reset (F-89258) clear it (+676 = 0 and the instance reset). `CarInstance::show_driver`.
//!
//! Read from every cine script (work/cutscenes2/driver/drvscan.py, the hash-named ones decrypted first): the
//! `push n` before each UseRacerNativeCharacter call (all constant) and the showdriver / hidedriver records (+12 car
