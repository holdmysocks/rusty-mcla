/// mcCareer_GetHookmanCharacterSet(`id`).
pub fn hookman_set(id: &str) -> Option<&'static str> {
    HOOKMAN_SETS.iter().find(|r| r.0.eq_ignore_ascii_case(id)).map(|r| r.1)
}

/// The mover label of `scene`'s car slot `slot`.
pub fn slot_label(scene: &str, slot: u8) -> Option<&'static str> {
    SLOT_MOVERS.iter().find(|r| r.1 == slot && r.0.eq_ignore_ascii_case(scene)).map(|r| r.2)
}

/// The set LoadDriver loads for the driver `name` (a key "drv_mb_02_set", or one of its loaded sets): hi-res or
/// `_lod02`, car or bike. None when `name` is in no map.
pub fn driver_set(name: &str, hi: bool, bike: bool) -> Option<&'static str> {
    let r = DRIVER_MAPS.iter().find(|r| [r.0, r.1, r.2, r.3, r.4].iter().any(|n| n.eq_ignore_ascii_case(name)))?;
    let s = match (hi, bike) {
        (true, false) => r.1,
        (true, true) => r.2,
        (false, false) => r.3,
        (false, true) => r.4,
    };
    (!s.is_empty()).then_some(s)
}

