//! Step 23b: the hangouts' scenes - what stands at a hangout and where the camera looks while
//! its panel is up, and the pink slip choice with the camera moving between the cars.
//!
//! The original (scripts read, `work/save/port/s23b/`):
//! - A hangout's set-up (`Game/Hangouts/<key>_setup`, local ones from +3280 of their block) holds
//!   +144 the number of the hangout's own cars, +220 their places, +320 their headings, +356
//!   their set-ups; +392 the first camera of the pink slip choice; +1328 the four pink slip
//!   spots and +1380 their headings; +1284 the set dressing; +396.. the people (characters,
//!   places, headings, animation packs and loops of the hangout's scene - the port's
//!   `cine::set_ambient` shows those loops). `HANGOUT_SETUPS` is generated from them
//!   (`s23b/gen_scene.py`).
//! - wager_hangout_core (`game/Hangouts/0x16e89a34`) 0x562..0x664 / local_hangout_core
//!   (`0xe166126d`) 0x2ea..: OpponentManager_CreateOpponent / LoadOpponent(set-up, place,
//!   heading) / AddOpponentToWorld for each of the hangout's cars, the driver off, no exhaust,
//!   no headlights, Racer_InitializeResetPosition + Racer_Reset at the place - the cars stand
//!   there while the set-up runs. The wager core's 0x9eb..0xbfa: the pink slip profiles
//!   (mcCareer_GetNumPinkSlipProfiles, at most 4) each loaded by its car config
//!   (LoadOpponentByCarConfig) at spot k, heading k, driver off, deactivated.
//! - Pulling in: LOCATION_EVENT runs `<key>_enter_cine` (cut_hangout_NN_ent_01 through
//!   core_rolling_prototype; its camera event `cam_to_menu` at 6.667 s), the core waits for the
//!   state 4 and shows its panel (form 62) - over the scene: the camera stays where the scene
//!   left it (the panel is flat, top left: `ref/hg_series_0`, `hg_wager_0`).
//! - PINKSLIP RACE (0x4b97..0x4ff3): the panel is closed (0x180b); the camera is the script's
//!   (UILogic_SetCameraControl(1)): target = spot k + (0, 0.5, 0), eye = target +
//!   UILogic_GetCameraPos(+392 + k) (= PauseCamera<+392 + k + 1>Position of the UILogic tune,
//!   world axes) + (0, 0.1, 0), Game_SetCamera(eye, target, 40); then every 30 ms (WAITUNWARPED
//!   30) eye and target each move toward their goal by fn 0x4d52: d = |goal - cur|; if d > 10 v:
//!   v = min(v + 0.004, 0.3) else v = min(0.9 v, d); cur += (goal - cur) / d x v. Buttons 13 / 3 /
//!   stick right step to profile k - 1, 15 / 2 / stick left to k + 1 (round, once per press);
//!   prompt 54 (VE_select_vehicle with the arrows, ACCEPT, BACK) or 55 with one profile; the
//!   string VE_select_vehicle = the profile's vehicle type name. 5 (BACK) leaves the choice for
//!   the panel, 6 (ACCEPT) asks the confirmation box (`mc4_pink_ask`).

