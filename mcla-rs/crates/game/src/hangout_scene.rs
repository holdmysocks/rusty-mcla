/// A car of a set-up standing still at its place (the driver off, deactivated).
fn stand_car(game: &mut Game, vehicles: &mut Vehicles, gpu: &mut Gpu, world: &mut World, model: &str, setup: &str, pos: Vec3, heading: f32, tag: String) -> bool {
    let m = match vehicles.models.iter().find(|m| m.name.eq_ignore_ascii_case(model)).cloned() {
        Some(m) => m,
        None => {
            let dir = world.assets.path("resources/vehicle").join(model);
            if !dir.is_dir() {
                log::warn!("hangout scene: no vehicle {}", model);
                return false;
            }
            match vehicles.load_model(gpu, world, &dir) {
                Ok(m) => m,
                Err(e) => {
                    log::warn!("hangout scene: {}: {}", model, e);
                    return false;
                }
            }
        }
    };
    let rgb = game.rivals.paint_of(setup);
    let color = rgb.map(|c| [c[0], c[1], c[2], 1.0]).unwrap_or([0.5, 0.5, 0.5, 1.0]);
    // (the headings are the race files' convention: the yaw itself, in degrees)
    let idx = vehicles.spawn(gpu, m, pos + Vec3::Y * 0.4, heading.to_radians(), color, false);
    let c = &mut vehicles.cars[idx];
    c.ai = None;
    c.pinned = true;
    c.placed = false;
    c.driver = tag;
    c.vinyl_name = setup.to_string();
    // (Racer_SetHeadlights(car, 0) of the hangout cores and the payback's set-up: its lamps switched off)
    c.amb_lamps.off = true;
    true
}

impl HangoutScene {
    /// Once a frame from the hangouts' block of the loop: `near` the nearest hangout's pull-in
    /// scene and its distance, `scene` the cine scene playing and its camera.
    pub fn update(&mut self, game: &mut Game, vehicles: &mut Vehicles, gpu: &mut Gpu, world: &mut World, near: Option<(&str, f32)>, scene: Option<&str>, cam: Option<(Vec3, Vec3, Vec3, f32)>, dt: f32) {
        self.tick = self.tick.wrapping_add(1);
        // (test hook: MCLA_PUT_AT="x,y,z[,yaw degrees]" puts the player's car there once, a
        // second into the run)
        if self.tick == 60 {
            if let Ok(v) = std::env::var("MCLA_PUT_AT") {
                let f: Vec<f32> = v.split(',').filter_map(|x| x.trim().parse().ok()).collect();
                if f.len() >= 3 {
                    if let Some(c) = vehicles.player_mut() {
                        c.state = crate::physics::CarState::new(Vec3::new(f[0], f[1] + 0.5, f[2]), f.get(3).copied().unwrap_or(0.0).to_radians());
                        c.placed = false;
                        c.pose_history.reset();
                        log::info!("MCLA_PUT_AT: the car put at {:?}", (f[0], f[1], f[2]));
                    }
                }
            }
        }
        // (the pull-in scene's last camera is held for the panel - cam_to_menu)
        if let (Some(sc), Some(c)) = (scene, cam) {
            if sc.contains("cut_hangout_") && sc.ends_with("_ent_01") {
                self.held = Some(c);
                self.held_key = crate::mc4::hangout_key_of_scene(sc.trim_end_matches("_ent_01")).map(|k| k.to_string());
            }
        }
        // (dropped once the hangout is left: its key goes with the panel)
        let panel = game.mode == Mode::RaceSelect && game.hangout_key.is_some() && game.hangout_key == self.held_key;
        if game.hangout_key != self.held_key && scene.map_or(true, |s| !s.ends_with("_ent_01")) {
            self.held = None;
            self.held_key = None;
        }
        // ---- the hangout's cars: while its set-up runs and the player is near ----
        let want = near.filter(|n| n.1 < 170.0).and_then(|n| crate::mc4::hangout_key_of_scene(n.0).filter(|_| game.mc4_hangout_open(n.0) || panel).map(|k| k.to_string()));
        let want = if game.race.is_some() { None } else { want };
        if want != self.cars_of {
            vehicles.cars.retain(|c| !c.driver.starts_with(TAG));
            self.stood.clear();
            self.pink_uids.clear();
            self.cars_of = None;
            if let Some(k) = want.as_ref().and_then(|k| setup_of(k)) {
                for (setup, p, h) in k.cars {
                    let model = crate::mc4::setup_vehicle(setup);
                    stand_car(game, vehicles, gpu, world, &model, setup, Vec3::from(*p), *h, format!("{TAG}{}", k.key));
                }
                log::info!("hangout scene: {} - {} cars of its set-up stand there", k.key, k.cars.len());
            }
            self.cars_of = want.clone();
        }
        // (the pink slip profiles at their spots - re-evaluated when they change, 0x9d6)
        if let Some(s) = self.cars_of.as_deref().and_then(setup_of).filter(|s| !s.pink.is_empty()) {
            let profiles = game.mc4_pink_profiles(s.key);
            let uids: Vec<i32> = profiles.iter().take(4).map(|p| p.uid).collect();
            if uids != self.pink_uids && self.tick % 30 == 0 {
                let tag = format!("{TAG}pink:{}", s.key);
                vehicles.cars.retain(|c| c.driver != tag);
                self.stood.retain(|s| s.0 .0 != tag);
                for (k, p) in profiles.iter().take(4).enumerate() {
                    let (spot, h) = s.pink[k];
                    let setup = game.mc4_pink_setup_name(p);
                    stand_car(game, vehicles, gpu, world, &p.car, &setup, Vec3::from(spot), h, tag.clone());
                }
                log::info!("hangout scene: {} pink slip profiles {:?} at their spots", s.key, uids);
                self.pink_uids = uids;
            }
        }
        // ---- the Beaches payback's place (payback_hangout_core 0x311..0x41c, 0x640..0x7f9) ----
        self.payback(game, vehicles, gpu, world, scene, dt);
        // (deactivated racers - Racer_Deactivate, the driver off: not driven, not moved. Once a
        // car has come down onto the ground its place is kept)
        for c in vehicles.cars.iter_mut().filter(|c| c.driver.starts_with(TAG)) {
            let key = (c.driver.clone(), c.model.name.clone());
            match self.stood.iter().position(|s| s.0 == key) {
                Some(k) => {
                    let (_, p, r) = self.stood[k].clone();
                    c.state.pos = p;
                    c.state.rot = r;
                    c.state.vel = Vec3::ZERO;
                    c.state.ang_vel = Vec3::ZERO;
                }
                None if c.placed => {
                    log::info!("hangout scene: {} ({}) stands at {:?}", key.0, key.1, c.state.pos);
                    self.stood.push((key, c.state.pos, c.state.rot));
                }
                None => {}
            }
        }
        // (a place is forgotten with its car: the payback's client's car stands with no hangout's cars out)
        if self.cars_of.is_none() {
            self.stood.retain(|s| vehicles.cars.iter().any(|c| c.driver == s.0 .0 && c.model.name == s.0 .1));
        }
        // ---- the pink slip choice ----
        let choosing = game.mode == Mode::RaceSelect && game.hangout_page.0 == 2 && game.opt_x.s23.hangout_hold.is_none();
        let setup = game.hangout_key.as_deref().and_then(setup_of).filter(|s| s.cam_base >= 0);
        match (choosing, setup) {
            (true, Some(s)) => {
                let n = game.mc4_pink_profiles(s.key).len().clamp(1, 4);
                let k = game.opt_x.arcade.pink.pick.min(n - 1);
                if self.pink.as_ref().map_or(true, |p| p.key != s.key) {
                    self.pink = PinkChoice::start(s, k);
                }
                if let Some(p) = self.pink.as_mut() {
                    p.tick(s, k, dt);
                }
            }
            _ => self.pink = None,
        }
    }

    /// The payback's place: the client's car standing (driver off, no headlights, icon 10)
    /// while the set-up runs; within 15 m, in the cruise, not chased (else LOSE_COPS): the
    /// police sent away, the player's car stopped (Racer_Deactivate), LOCATION_EVENT and
    /// MISSION_EVENT BE_PAYBACK_ENTER (GARAGE_BEACHES' PAYBACK_INTRO scene when it waits for
    /// it), the core waits while the place's state is 3; then tTPA (form 101, slow motion) and
    /// the payback's panel (form 68 - the port's `be_payback` panel). Left by more than 40 m:
    /// the set-up has ended, its restarter waits (`mc4_hangout_left`).
    fn payback(&mut self, game: &mut Game, vehicles: &mut Vehicles, gpu: &mut Gpu, world: &mut World, scene: Option<&str>, dt: f32) {
        let Some(p) = vehicles.player().map(|c| c.state.pos) else { return };
        let at = Vec3::from(PAYBACK_AT);
        let d = p.distance(at);
        let open = game.mc4_place_open("be_payback");
        let tag = format!("{TAG}be_payback");
        let here = vehicles.cars.iter().any(|c| c.driver == tag);
        let want = open && d < 170.0 && game.race.is_none();
        if want && !here {
            let (setup, cp, h) = PAYBACK_CAR;
            stand_car(game, vehicles, gpu, world, &crate::mc4::setup_vehicle(setup), setup, Vec3::from(cp), h, tag.clone());
            log::info!("payback place: the client's car stands there ({:.0} m)", d);
        } else if !want && here {
            vehicles.cars.retain(|c| c.driver != tag);
            self.stood.retain(|s| s.0 .0 != tag);
        }
        if self.pay_away && d > 40.0 {
            self.pay_away = false;
            if self.pay_step != 0 {
                self.pay_step = 0;
                game.mc4_hangout_left("be_payback");
                log::info!("payback place: left");
            }
        }
        match self.pay_step {
            0 => {
                let pursued = matches!(game.opt_x.s23.heat_was, 2 | 3);
                let free = game.mode == Mode::FreeRoam && game.race.is_none() && scene.is_none() && game.hangout_key.is_none();
                if open && free && !self.pay_away && d < PAYBACK_RADIUS {
                    if pursued {
                        let m = game.career.strings.get("LOSE_COPS").map(|s| s.to_uppercase()).unwrap_or_else(|| "LOSE THE COPS".into());
                        game.show_message(&m);
                        self.pay_away = true;
                        return;
                    }
                    if let Some(c) = vehicles.player_mut() {
                        c.state.vel = Vec3::ZERO;
                        c.state.ang_vel = Vec3::ZERO;
                    }
                    if let Some(sc) = game.career.location_enter("BE_PAYBACK_ENTER") {
                        game.career.news.push(crate::career::News::Scene(sc));
                    }
                    self.pay_step = 1;
                    self.pay_wait = 0.0;
                    self.pay_away = true;
                    log::info!("payback place: pulled in ({:.1} m) - LOCATION_EVENT 513, BE_PAYBACK_ENTER", d);
                }
            }
            1 => {
                // (the scene, if one is due, comes up through the career's news; the panel after it)
                self.pay_wait += dt;
                if self.pay_wait > 1.0 && scene.is_none() && game.mode == Mode::FreeRoam {
                    game.mc4_payback_place_panel(p);
                    self.pay_step = 2;
                }
            }
            _ => {}
        }
    }

    /// The camera the hangout holds: the pink slip choice's, else the pull-in scene's last
    /// frame while the panel is up. (eye, look-at, up, vertical fov in radians)
    pub fn camera(&self, game: &Game) -> Option<(Vec3, Vec3, Vec3, f32)> {
        if let Some(p) = self.pink.as_ref() {
            return Some((p.eye, p.look, Vec3::Y, 40f32.to_radians()));
        }
        let panel = game.mode == Mode::RaceSelect && game.hangout_key.is_some() && game.hangout_key == self.held_key;
        if panel {
            return self.held.map(|(eye, fwd, up, fov)| (eye, eye + fwd, up, fov));
        }
        None
    }
}

impl Game {
    /// The pink slip choice (wager_hangout_core 0x4b97..0x4ff8) in place of the port's panel
    /// page: the panel closed, the prompt bar with the profile's vehicle (prompt 54: the name
    /// between arrows, ACCEPT (A), BACK (B); 55 without the arrows when there is one profile);
    /// stick / d-pad right steps to the profile before, left to the one after (round); ACCEPT
    /// asks the confirmation box, BACK goes back to the panel's PINKSLIP RACE row. The camera
    /// is `HangoutScene`'s.
    pub fn mc4_pink_choice_ui(&mut self, ctx: &egui::Context, key: &str, left: bool, right: bool, enter: bool, back: bool) -> Option<crate::game::MenuAction> {
        use crate::flash_ui::{ICON_A, ICON_ARROWS, ICON_B};
        if let Some(fm) = self.flash_menu.as_mut() {
            fm.hide();
        }
        let profiles = self.mc4_pink_profiles(key);
        let n = profiles.len().min(4);
        let leave = |this: &mut Self| {
            this.hangout_page = (0, 1);
            if let Some(fp) = this.flash_prompt.as_mut() {
                fp.hide();
            }
        };
        if n == 0 {
            leave(self);
            return None;
        }
        // (the box is up: the choice waits for its answer - 0x4ff8..0x5095)
        let asking = self.message_box.is_some() || self.opt_x.s23.pink_ask.is_some();
        let pick = &mut self.opt_x.arcade.pink.pick;
        if !asking {
            if right {
                *pick = (*pick + n - 1) % n;
            }
            if left {
                *pick = (*pick + 1) % n;
            }
        }
        let pick = self.opt_x.arcade.pink.pick.min(n - 1);
        let st = |k: &str, d: &str| self.career.strings.get(k).map(|v| v.to_uppercase()).filter(|v| !v.contains('<')).unwrap_or_else(|| d.to_string());
        let car = &profiles[pick].car;
        let name = self.career.strings.get(car).map(|s| s.to_uppercase()).unwrap_or_else(|| crate::game::pretty_car_name(car).to_uppercase());
        let prompts = vec![(name, if n > 1 { ICON_ARROWS } else { 0 }), (st("prompt_accept", "ACCEPT"), ICON_A), (st("prompt_back", "BACK"), ICON_B)];
        let dt = ctx.input(|i| i.stable_dt).min(0.1);
        if let Some(fp) = self.flash_prompt.as_mut() {
            fp.movie.player.set_global("vehicle_select", mcla_flash::value::Value::Int(0));
            fp.show(&prompts, None, None);
            fp.movie.player.update(dt);
            let layer = egui::LayerId::new(egui::Order::Foreground, egui::Id::new("pink_choice"));
            fp.movie.paint(ctx, &ctx.layer_painter(layer));
        }
        if asking {
            return None;
        }
        // (test hook: MCLA_PINK_ACCEPT presses ACCEPT here)
        if enter || std::env::var("MCLA_PINK_ACCEPT").is_ok() {
            // (UI_MENU_SELECT; the box - its YES stakes and starts the race)
            self.mc4_pink_ask(key, pick);
            return None;
        }
        if back {
            leave(self);
        }
        None
    }

    /// A hangout's tutorial over its scene (the cores show their form before the panel and
    /// wait for it - 0x166b, 0x4b17; the delivery's / payback's with the slow motion): the
    /// box with CONTINUE (A) on the popup movie, the panel held. True while it holds the panel.
    pub fn mc4_hangout_tut_ui(&mut self, ctx: &egui::Context, enter: bool) -> bool {
        if self.opt_x.s23.hangout_hold.is_none() {
            return false;
        }
        let Some((title, text, wait, left)) = self.tutorial_box.clone() else { return true };
        let dt = ctx.input(|i| i.stable_dt).min(0.1);
        let left = if self.mc4_tut_continue(&title) && wait <= 0.0 && enter { 0.0 } else { left };
        if left <= 0.0 {
            self.tutorial_box = None;
            if let Some(fp) = self.flash_popup.as_mut() {
                fp.hide();
            }
            return true;
        }
        if wait > 0.0 {
            self.tutorial_box = Some((title, text, wait - dt, left));
            return true;
        }
        let st = |k: &str| self.career.strings.get(k).map(|v| v.to_string()).unwrap_or_default();
        let prompts = vec![(self.career.strings.get("prompt_continue").map(|v| v.to_uppercase()).unwrap_or_else(|| "CONTINUE".into()), crate::flash_ui::ICON_A)];
        let page = crate::flash_ui::MenuPage { layout: crate::flash_ui::MenuLayout::Tutorial { description: st(&text) }, title: st(&title), select: usize::MAX, prompts, ..Default::default() };
        if let Some(fp) = self.flash_popup.as_mut() {
            fp.show(&page);
            fp.movie.player.update(dt);
            fp.movie.paint(ctx, &ctx.layer_painter(egui::LayerId::new(egui::Order::Foreground, egui::Id::new("tutorial"))));
        }
        self.tutorial_box = Some((title, text, 0.0, left - dt));
        true
    }
}

impl Game {
    /// (step 23b) A place's set-up runs and no restarter waits for it (by its key).
    pub fn mc4_place_open(&self, key: &str) -> bool {
        self.mc4_setup_shown(&crate::mc4::marker_script(0, key)) && !self.car_x.hangout_wait.iter().any(|w| w == key)
    }

    /// (step 23b) The payback's panel at its place: the run's first leg is the payback race
    /// nearest the player that the run has not had (PaybackCore's mcRaceArray_SortByDistance /
    /// FindNextRaceIndex - the same as its next legs), the panel on EASIEST.
    pub fn mc4_payback_place_panel(&mut self, from: Vec3) {
        let mut list: Vec<usize> = (0..self.race_defs.len()).filter(|&i| self.race_defs[i].race_type == "Payback").collect();
        list.sort_by(|a, b| self.race_defs[*a].beacon.distance(from).partial_cmp(&self.race_defs[*b].beacon.distance(from)).unwrap_or(std::cmp::Ordering::Equal));
        let Some(&first) = list.first() else { return };
        self.current_race = Some(first);
        self.hangout_diff = 0;
        self.hangout_key = Some("be_payback".to_string());
        self.hangout_page = (0, 0);
        self.mode = Mode::RaceSelect;
        log::info!("payback place: its panel, first leg {}", self.race_defs[first].id);
    }
}
