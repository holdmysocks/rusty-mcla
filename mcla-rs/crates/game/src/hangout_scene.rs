/// UILogic_GetCameraPos(i) (sub_8220D5B0: UILogic + (i + 4897) x 16 = PauseCamera<i + 1>Position).
pub fn camera_pos(i: i32) -> Option<Vec3> {
    PAUSE_CAMERA_POS.iter().find(|p| p.0 as i32 == i + 1).map(|p| Vec3::from(p.1))
}

pub fn setup_of(key: &str) -> Option<&'static HangoutSetup> {
    HANGOUT_SETUPS.iter().find(|s| s.key.eq_ignore_ascii_case(key))
}

/// The pink slip choice's camera goal for profile `k`: (eye, target).
pub fn pink_goal(s: &HangoutSetup, k: usize) -> Option<(Vec3, Vec3)> {
    let (spot, _) = s.pink.get(k)?;
    let target = Vec3::from(*spot) + Vec3::Y * 0.5;
    let eye = camera_pos(s.cam_base + k as i32)? + target + Vec3::Y * 0.1;
    Some((eye, target))
}

/// fn 0x4d52 of wager_hangout_core: one 30 ms step of `cur` toward `goal` at speed `v`.
pub fn step_toward(cur: &mut Vec3, goal: Vec3, v: &mut f32) {
    let d = cur.distance(goal);
    if d > *v * 10.0 {
        *v = (*v + 0.004).min(0.3);
    } else {
        *v *= 0.9;
        if *v > d {
            *v = d;
        }
    }
    if d > 0.0 {
        *cur += (goal - *cur) / d * *v;
    }
}

/// The pink slip choice under way.
#[derive(Clone, Debug)]
pub struct PinkChoice {
    pub key: String,
    pub eye: Vec3,
    pub look: Vec3,
    pub v_eye: f32,
    pub v_look: f32,
    pub acc: f32,
}

impl PinkChoice {
    /// 0x4bcb..0x4c1d: the camera put on profile `k` at once.
    pub fn start(s: &HangoutSetup, k: usize) -> Option<PinkChoice> {
        let (eye, look) = pink_goal(s, k)?;
        Some(PinkChoice { key: s.key.to_string(), eye, look, v_eye: 0.0, v_look: 0.0, acc: 0.0 })
    }

    /// The loop's steps (one every 30 ms) toward profile `k`.
    pub fn tick(&mut self, s: &HangoutSetup, k: usize, dt: f32) {
        let Some((eye, look)) = pink_goal(s, k) else { return };
        self.acc += dt;
        while self.acc >= 0.03 {
            self.acc -= 0.03;
            step_toward(&mut self.look, look, &mut self.v_look);
            step_toward(&mut self.eye, eye, &mut self.v_eye);
        }
    }
}

